-- =====================================================================
-- Smart Mappia — Migration 0033: persist heading + speed on driver GPS
-- For: Supabase / PostgreSQL 15+
--
-- The moving-car map re-derived the vehicle's facing direction on the
-- client from two consecutive fixes 12s apart (bearingDeg in
-- frontend/src/portal/lib/geo.js). That is coarse, jitters whenever GPS
-- wanders while the car is stopped, and resets to 0 (due north) on every
-- page reload because nothing about direction was ever stored.
--
-- The device already knows better: both the browser Geolocation API and
-- the Capacitor plugin report coords.heading and coords.speed straight
-- off the chip. There was simply nowhere to put them — driver_locations
-- has carried only lat/lng/accuracy since 0001.
--
-- To run it: Supabase Dashboard -> SQL Editor -> paste this in -> Run.
-- Safe to re-run.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. The two new columns.
--
--    Both NULLABLE on purpose, and every reader must cope with null:
--      * desktop browsers report heading/speed as null always (no compass,
--        no dead-reckoning),
--      * phones report heading as null while STATIONARY — a parked car has
--        a position but no direction of travel.
--    So null is the normal case, not a data-quality problem. The client
--    keeps bearingDeg() as the fallback for exactly these rows.
--
--    heading is degrees clockwise from true north, 0..360 (the chip's own
--    convention — we store it unchanged rather than normalising to the
--    -180..180 that bearingDeg returns, so the raw reading stays legible).
--    speed_kmh is km/h; the API reports m/s and the backend converts.
-- ---------------------------------------------------------------------
alter table driver_locations add column if not exists heading   double precision;
alter table driver_locations add column if not exists speed_kmh double precision;

comment on column driver_locations.heading is
  'Degrees clockwise from true north (0..360), straight from the device. NULL when stationary or unsupported — clients fall back to a bearing derived from two fixes.';
comment on column driver_locations.speed_kmh is
  'Ground speed in km/h, converted from the device''s m/s reading. NULL when unsupported.';

-- ---------------------------------------------------------------------
-- 2. Finish the 0030 lockdown on this table — it was missed.
--
--    0030 revoked the default table-wide write grants on profiles,
--    menu_items, products, product_variants and merchants. It did NOT
--    cover driver_locations, so this table still carries PostgreSQL's
--    default grants: `anon` and `authenticated` hold INSERT/UPDATE/DELETE
--    on every column, now including the two added above.
--
--    Measured, not assumed (2026-08-02, against the live database):
--      anon INSERT -> 42501, rejected by RLS
--      anon UPDATE on a real row -> succeeds but affects 0 ROWS
--
--    So this is NOT a live hole today: RLS is enabled and the only policy
--    is driver_locations_self, which is FOR SELECT. With no UPDATE policy,
--    an update sees no rows. It is dormant, and dormant is precisely the
--    state 0030 was written to stop relying on — its own changelog phrases
--    the risk as "only RLS blocks it".
--
--    It matters here because the trap is one edit away. The day anyone
--    adds a legitimate UPDATE policy (say, "a driver may correct their own
--    fix"), this grant goes live over EVERY column at once — including
--    heading and speed_kmh, which feed the customer's live map.
--
--    Nothing needs client-side write access: driver GPS arrives only via
--    POST /api/driver/location and is written by the service role, which
--    grants do not constrain. So revoke writes outright rather than
--    granting a column list back the way merchants/profiles needed.
--    SELECT is deliberately left in place — it is already RLS-scoped to
--    "your own rows or admin" and revoking it would be a behaviour change
--    beyond this migration's remit.
-- ---------------------------------------------------------------------
revoke insert, update, delete on table driver_locations from anon, authenticated;

